#!/usr/bin/env python3
"""Build a complete 101-scene candidate tree without modifying the base or source repository."""
import argparse,csv,hashlib,json,pathlib,shutil,subprocess,sys,tempfile

def sha(path):
 h=hashlib.sha256()
 with path.open('rb') as f:
  for b in iter(lambda:f.read(4*1024*1024),b''):h.update(b)
 return h.hexdigest()

def inside(root,relative):
 p=pathlib.PurePosixPath(relative)
 if p.is_absolute() or '..' in p.parts or '\\' in relative:raise ValueError('Unsafe path')
 result=root.joinpath(*p.parts)
 if any(x.is_symlink() for x in [result,*result.parents]):raise ValueError('Symlink not allowed')
 return result

def main():
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--repo',required=True,type=pathlib.Path);ap.add_argument('--base',required=True,type=pathlib.Path);ap.add_argument('--output',required=True,type=pathlib.Path);a=ap.parse_args()
 repo=a.repo.resolve();base=a.base.resolve();out=a.output.absolute()
 if out.exists():ap.error('Output must not exist')
 if base==out or base in out.parents or out in base.parents:ap.error('Output must be separate from baseline')
 rows=list(csv.DictReader((repo/'ASSET_FILE_INDEX_20261013.csv').open(encoding='utf-8-sig')))
 expected={r['path']:r for r in rows}
 actual={p.relative_to(base).as_posix() for p in (base/'assets').rglob('*') if p.is_file()}
 if actual!=set(expected):raise ValueError('Baseline missing or extra asset paths')
 for r in rows:
  p=inside(base,r['path'])
  if p.stat().st_size!=int(r['bytes']) or sha(p)!=r['sha256']:raise ValueError('Baseline hash mismatch: '+r['path'])
 candidate=repo/'candidates/20261118';changes=json.loads((candidate/'manifest.json').read_text())
 for c in changes:
  if c['path'] not in expected or c['baseline_sha256']!=expected[c['path']]['sha256']:raise ValueError('Candidate baseline mismatch')
 with tempfile.TemporaryDirectory(prefix='campus-verified-',dir=out.parent) as temp:
  unpack=pathlib.Path(temp)/'unpacked'
  subprocess.run([sys.executable,str(candidate/'extract_candidates.py'),'--output',str(unpack)],check=True)
  for c in changes:
   p=inside(unpack,c['path'])
   if sha(p)!=c['sha256']:raise ValueError('Candidate source mismatch')
  # Every source is checked before the new tree is created. The baseline remains read-only.
  shutil.copytree(base,out)
  for c in changes:shutil.copy2(inside(unpack,c['path']),inside(out,c['path']))
  final=[]
  for r in rows:
   p=inside(out,r['path']);final.append({'path':r['path'],'bytes':p.stat().st_size,'sha256':sha(p)})
  changed={c['path']:c for c in changes}
  for r in final:
   wanted=changed[r['path']]['sha256'] if r['path'] in changed else expected[r['path']]['sha256']
   if r['sha256']!=wanted:raise ValueError('Final hash mismatch: '+r['path'])
  receipt={'scope':'Complete candidate source tree; not game accepted','base_asset_count':len(rows),'changed_source_count':len(changes),'blend_count':sum(r['path'].endswith('.blend') for r in final),'unchanged_asset_count':len(rows)-len(changes),'game_editor_verified':False,'warning':'Existing baseline FBX exports are historical and are not regenerated by this source-tree assembly. Do not call them exports of the changed 11 Blender candidates.','assets':final}
  (out/'CANDIDATE_SOURCE_MANIFEST_20261118.json').write_text(json.dumps(receipt,ensure_ascii=False,indent=2))
  print(json.dumps({k:v for k,v in receipt.items() if k!='assets'},ensure_ascii=False))
if __name__=='__main__':main()
